"""Generate closed DSL deployment types/validation metadata from the shared API."""
from __future__ import annotations

import argparse
import keyword
from pathlib import Path
from pprint import pformat

import yaml


def render(source: Path) -> str:
    all_schemas = yaml.safe_load(source.read_text())["components"]["schemas"]
    selected = {}

    def collect(name):
        if name in selected:
            return
        selected[name] = all_schemas[name]
        visit(selected[name])

    def visit(value):
        if isinstance(value, dict):
            if value.get("additionalProperties") is True:
                raise ValueError("Opaque deployment objects are unsupported")
            if "$ref" in value:
                prefix = "#/components/schemas/"
                if not value["$ref"].startswith(prefix):
                    raise ValueError("Only local deployment references are supported")
                collect(value["$ref"][len(prefix):])
            for item in value.values():
                visit(item)
        elif isinstance(value, list):
            for item in value:
                visit(item)

    collect("DeploymentSettings")

    def annotation(schema):
        if "$ref" in schema:
            return schema["$ref"].rsplit("/", 1)[1]
        if "oneOf" in schema:
            return " | ".join(annotation(item) for item in schema["oneOf"])
        kind = schema.get("type")
        if kind == "array":
            return f"Sequence[{annotation(schema['items'])}]"
        if kind == "object":
            return f"Mapping[str, {annotation(schema['additionalProperties'])}]"
        return {"integer": "int", "number": "float", "boolean": "bool", "string": "str"}[kind]

    lines = ['"""Generated by scripts/sync_deployment_contract.py; do not edit."""',
             "from __future__ import annotations", "", "from collections.abc import Mapping, Sequence",
             "from typing import TypedDict", ""]
    aliases = []
    for name, schema in sorted(selected.items()):
        if "properties" not in schema:
            aliases.append(f"{name} = {annotation(schema)}")
            continue
        lines.append(f"class {name}(TypedDict, total=False):")
        for key, child in schema["properties"].items():
            if not key.isidentifier() or keyword.iskeyword(key):
                raise ValueError("Deployment property requires unsupported Python spelling")
            lines.append(f"    {key}: {annotation(child)}")
        lines.extend(["", ""])
    # All named records exist before evaluating map/scalar aliases.
    lines.extend(aliases)
    lines.extend(["", "SCHEMAS = " + pformat(dict(sorted(selected.items())), width=100, sort_dicts=True), ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "src/sa_dsl/_deployment_contract.py"
    content = render(args.source)
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit("Deployment contract is stale; run this script without --check")
    else:
        target.write_text(content)
